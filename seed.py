def main():
    server.init_db()
    db = server.get_db()
    if db.execute("SELECT COUNT(*) FROM requests").fetchone()[0]:
        print("factory.db כבר מכיל נתונים — מדלג על seed.")
        return
    with db:
        for text, sent, status in SAMPLES:
            fields = req_parser.parse_request(text, ref=sent)
            if status:
                fields["status"] = status
            rid = server.create_request(db, fields, actor="seed")
            if status == "הושלמה":
                db.execute("UPDATE requests SET completed_at=? WHERE id=?",
                           (fields.get("due_date", ""), rid))
    print("נטענו %d בקשות דוגמה." % len(SAMPLES))


if __name__ == "__main__":
    main()
